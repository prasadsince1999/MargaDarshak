/// Margadarshak icon size tokens.
///
/// Source: 14-design-tokens.md + 07-icons-illustrations.md
///
/// Rules:
///   - Use Material Icons Rounded variant.
///   - Never rely on color alone; always pair icons with text labels.
abstract final class AppIconSizes {
  /// 16dp — inline text icons, small indicators
  static const double sm = 16;

  /// 20dp — standard button/list icons
  static const double md = 20;

  /// 24dp — navigation, cards, primary actions
  static const double lg = 24;

  /// 32dp — hero icons, onboarding, empty states
  static const double xl = 32;
}
